/**
 * เนื้อหาความรู้เรื่องอัลกอริทึม — ผูกกับของจริงในโปรเจกต์นี้ทุกหัวข้อ
 *
 * แบ่งเป็นสามกลุ่มตามความจริง ไม่ใช่ตามความยาก:
 *   blocks  = ต่อด้วยบล็อกได้เองตอนนี้ กดดูตัวอย่างจริงได้
 *   engine  = ระบบใช้อยู่เบื้องหลัง เด็กไม่ได้เขียนเอง แต่เห็นผลมันทุกครั้งที่เล่น
 *   concept = ควรรู้จักไว้ แต่ยังไม่มีในเกมนี้ และมีเหตุผลว่าทำไม
 */
export type TopicGroup = 'blocks' | 'engine' | 'concept'

export interface TopicPreset {
  game: 'maze' | 'othello'
  id: string
}

/** ที่มาทางวิชาการ — ต้องอ้างของจริงที่ตรวจสอบได้ ไม่ใช่เขียนลอย ๆ */
export interface Theory {
  /** เล่าที่มาเป็นเรื่อง — ตอนนั้นติดปัญหาอะไร ใครแก้ แก้ยังไง แล้วเกิดอะไรตามมา */
  origin: string[]
  /** ทำไมวิธีนี้ถึงได้ผล (หรือไม่ได้ผล) — เหตุผลเบื้องหลัง เขียนแบบไม่ใช้สูตร */
  why: string[]
  /** งานต้นฉบับที่อ้างถึงได้ */
  papers: Array<{ cite: string; note?: string }>
  /** ความซับซ้อนแบบสัญกรณ์ O ใหญ่ พร้อม plain = คำแปลเป็นภาษาคนกับตัวเลขจริงในเกมนี้ */
  bigO: { time: string; space: string; plain: string }
  /** รับประกันอะไร ภายใต้เงื่อนไขอะไร */
  guarantee?: string
}

export interface Topic {
  slug: string
  name: string
  english: string
  tagline: string
  group: TopicGroup
  /** อธิบายว่ามันคืออะไร แบบไม่ใช้ศัพท์เทคนิคก่อน */
  what: string[]
  /** ขั้นตอนการทำงาน เรียงตามลำดับ */
  steps: string[]
  /** เกี่ยวอะไรกับเกมนี้ — ต้องเป็นเรื่องจริงที่ตรวจสอบได้ */
  inGame: string
  /** ตัวอย่างบล็อกที่กดดูได้ (เฉพาะกลุ่ม blocks) */
  preset?: TopicPreset
  /** ไฟล์จริงในโปรเจกต์ (เฉพาะกลุ่ม engine) */
  source?: string
  /** ทำไมยังต่อด้วยบล็อกไม่ได้ (เฉพาะกลุ่ม concept) */
  blocker?: string
  cost: { time: string; space: string }
  theory: Theory
  /** ข้อดี/ข้อเสียที่เห็นได้จริงตอนเล่น */
  good: string
  bad: string
}

