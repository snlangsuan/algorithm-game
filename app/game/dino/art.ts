/**
 * นกมาทีละตัวหรือเป็นฝูงสองตัว และบินสูงต่ำไม่เท่ากัน — แต่ทุกแบบต้องผ่านได้เสมอ
 *
 * กติกาเดียวที่ห้ามพัง: ทุกฝูง "หมอบลอดได้" (ขอบล่างสูงกว่าหัวตอนหมอบ)
 * หรือ "กระโดดข้ามได้" (ยอดไม่สูงกว่าของบนพื้นที่สูงที่สุดเกิน 2 พิกเซล) อย่างใดอย่างหนึ่ง
 * ไม่มีความสูงช่วงกลางที่หมอบก็ชน กระโดดก็ชน เพราะนั่นไม่ใช่ความยาก แต่เป็นกับดักที่ไม่มีทางรอด
 *
 * - ตัวเดียวบินต่ำ: เรี่ยพื้น ต้องกระโดด เหมือนของบนพื้นชิ้นหนึ่ง
 * - ตัวเดียวบินกลาง/สูง: หมอบลอดได้ บางระดับสูงพอให้วิ่งลอดไปเฉย ๆ แต่กระโดดใส่คือชน
 * - ฝูงสองตัว: สูง 52 เกินกว่ากระโดดพ้น (ขึ้นได้ 53 แต่ต้องพ้นทั้งตัว) ต้องหมอบลอดเท่านั้น
 */
